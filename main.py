from modelo.caracteristicas import COLUMNAS_NUMERICAS, COLUMNAS_CATEGORICAS, obtener_categorias, codificar_one_hot, obtener_limites_numericos, normalizar_numericas
ruta = Path(__file__).resolve().parent / 'datos' / 'SouthGermanCredit.asc'
with open(ruta, 'r', encoding='utf-8-sig') as archivo:
    lineas = archivo.readlines()
cabecera = tuple(lineas[0].strip().split())
registros = tuple(map(lambda linea: tuple(map(int, linea.strip().split())), lineas[1:]))
total_ausentes = contar_ausentes(registros)
registros_prueba = simular_ausentes(registros)
montos = tuple(map(lambda registro: registro[4], registros_prueba))
mediana_montos = calcular_mediana(montos)
registros_imputados = imputar_columna(registros_prueba, 4, mediana_montos)
q1, q3, iqr, minimo, maximo = calcular_iqr(registros_imputados, 4)
registros_filtrados = filtrar_outliers(registros_imputados, 4, minimo, maximo)
min_monto, max_monto = calcular_min_max(registros_filtrados, 4)
registros_normalizados = normalizar_min_max(registros_filtrados, 4, min_monto, max_monto)
registros_pipeline = pipe(registros_prueba, lambda datos: imputar_columna(datos, 4, mediana_montos), lambda datos: filtrar_outliers(datos, 4, minimo, maximo), lambda datos: normalizar_min_max(datos, 4, min_monto, max_monto))
datos_entrenamiento, datos_prueba = dividir_datos(registros_prueba, proporcion=0.8, semilla=42)
entrenamiento_2, prueba_2 = dividir_datos(registros_prueba, proporcion=0.8, semilla=42)
montos_entrenamiento = tuple(map(lambda registro: registro[4], datos_entrenamiento))
mediana_entrenamiento = calcular_mediana(montos_entrenamiento)
entrenamiento_imputado = imputar_columna(datos_entrenamiento, 4, mediana_entrenamiento)
prueba_imputada = imputar_columna(datos_prueba, 4, mediana_entrenamiento)
q1_train, q3_train, iqr_train, min_iqr, max_iqr = calcular_iqr(entrenamiento_imputado, 4)
entrenamiento_filtrado = filtrar_outliers(entrenamiento_imputado, 4, min_iqr, max_iqr)
min_train, max_train = calcular_min_max(entrenamiento_filtrado, 4)
entrenamiento_final = normalizar_min_max(entrenamiento_filtrado, 4, min_train, max_train)
prueba_final = normalizar_min_max(prueba_imputada, 4, min_train, max_train)
entrenamiento_modular, prueba_modular = preparar_datos(datos_entrenamiento, datos_prueba, columna=4)
X_train, y_train = separar_caracteristicas_etiquetas(entrenamiento_modular)
X_test, y_test = separar_caracteristicas_etiquetas(prueba_modular)
categorias = obtener_categorias(X_train)
X_train_categorico = codificar_one_hot(X_train, categorias)
X_test_categorico = codificar_one_hot(X_test, categorias)
minimos, maximos = obtener_limites_numericos(X_train)
X_train_numerico = normalizar_numericas(X_train, minimos, maximos)
X_test_numerico = normalizar_numericas(X_test, minimos, maximos)
X_train_final = unir_caracteristicas(X_train_numerico, X_train_categorico)
X_test_final = unir_caracteristicas(X_test_numerico, X_test_categorico)
matriz_distancias = calcular_distancias_euclidianas(X_test_final, X_train_final)
k = 5
indices_vecinos = obtener_vecinos_cercanos(matriz_distancias, k)
predicciones = votacion_mayoritaria(indices_vecinos, y_train)
predicciones_knn = predecir_knn(X_train_final, y_train, X_test_final, k=5)
matriz_confusion = calcular_matriz_confusion(y_test, predicciones_knn)
metricas = calcular_metricas(matriz_confusion)
edades_test = X_test[:, 12]
resultado_equidad = calcular_disparate_impact(edades_test, predicciones_knn)
resultado_grupos = calcular_exactitud_por_grupo(edades_test, y_test, predicciones_knn)
resultado_fn = calcular_falsos_negativos_por_grupo(edades_test, y_test, predicciones_knn)
